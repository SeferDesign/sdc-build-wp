test('log output is classified, collected for summaries and can be redirected to stderr', async t => {
	const out = [];
	const err = [];
	t.mock.method(console, 'log', (...args) => out.push(args.join(' ')));
	t.mock.method(console, 'warn', (...args) => err.push(['warn', args.join(' ')]));
	t.mock.method(console, 'error', (...args) => err.push(['error', args.join(' ')]));
	swap(t, project, { buildErrors: [], buildWarnings: [], argv: {}, builds: [], isRunning: false });
	log('php', 'from php');
	log('info', 'hello');
	log('success', 'done');
	log('warn', 'careful');
	log('error', 'broken');
	assert.equal(out.length, 3);
	// Terminals add color codes; the text must match either way.
	const plain = out.map(line => stripVTControlCharacters(line));
	assert.match(plain[0], /PHP:\s+from php/);
	assert.match(plain[1], /hello/);
	assert.match(plain[2], /done/);
	assert.deepEqual(err.map(([type]) => type), ['warn', 'error']);
	assert.deepEqual(project.buildWarnings, [{ component: null, message: 'careful' }]);
	assert.deepEqual(project.buildErrors, [{ component: null, message: 'broken' }]);

	project.argv = { json: true };
	out.length = 0;
	err.length = 0;
	log('info', 'to stderr');
	assert.deepEqual(out, []);
	assert.match(stripVTControlCharacters(err[0][1]), /to stderr/);
	assert.equal(err[0][0], 'error', 'JSON mode sends every level to stderr');

	let notified;
	swap(t, project, { argv: {}, builds: ['server'], isRunning: true, components: { server: { server: { notify: message => { notified = message; } } } } });
	log('error', 'visible in the browser');
	assert.equal(notified, 'ERROR');
});

test('agents prompt accepts numbers and names, cancels otherwise, and needs a terminal', async t => {
	const original = Object.getOwnPropertyDescriptor(process.stdin, 'isTTY');
	await assert.rejects(promptAgentsChoice(), /Interactive prompt unavailable/);
	Object.defineProperty(process.stdin, 'isTTY', { value: true, configurable: true });
	t.after(() => { if (original) { Object.defineProperty(process.stdin, 'isTTY', original); } else { delete process.stdin.isTTY; } });
	let answer;
	let closed = 0;
	t.mock.method(readline, 'createInterface', () => ({ question: async () => answer, close: () => { closed++; } }));
	const results = [];
	for (answer of ['1', ' Reference ', '2', 'COPY', 'q', '']) {
		results.push(await promptAgentsChoice());
	}
	assert.deepEqual(results, ['reference', 'reference', 'copy', 'copy', null, null]);
	assert.equal(closed, 6);
});

