test('warn mode checks syntax only, reloads the page and reports syntax errors', { skip: !hasPHP && 'php is not installed' }, async t => {
	const root = await withProject(t, { config: {} });
	const good = path.join(root, 'good.php');
	const bad = path.join(root, 'bad.php');
	await fs.writeFile(good, '<?php   echo   1;\n');
	await fs.writeFile(bad, '<?php echo ;\n');
	const component = new PHPComponent();
	const logs = [];
	component.log = (type, message) => logs.push({ type, message });
	let reloads = 0;
	component.project = { ...project, path: root, components: { server: { server: { reload: () => { reloads++; } } } } };
	await component.build(good, { lintType: 'warn' });
	assert.equal(await fs.readFile(good, 'utf8'), '<?php   echo   1;\n', 'warn mode never rewrites the file');
	assert.equal(reloads, 1);
	assert.ok(logs.some(entry => entry.type === 'success' && /Linted \(warn\)/.test(entry.message)));
	assert.equal(await component.build(bad, { lintType: 'warn' }), false);
	assert.equal(reloads, 1);
	assert.ok(logs.some(entry => entry.type === 'error' && /Failed to validate \/bad\.php/.test(entry.message)));
	component.globs = [good, bad];
	assert.equal(await component.build(), false, 'one syntax error fails a batch');
});

test('stopping components reports each failure and still releases everything else', async t => {
	const flushed = [];
	const stopped = [];
	const lines = [];
	t.mock.method(console, 'error', (...args) => lines.push(args.join(' ')));
	t.mock.method(console, 'log', () => {});
	swap(t, project, {
		configWatcher: { close: async () => { throw new Error('close failed'); } },
		validationWatcher: { stopWatching: async () => { stopped.push('validation'); } },
		components: {
			server: { server: { exit: () => { throw new Error('exit failed'); } } },
			cache: { flushManifest: async () => { flushed.push(true); } },
			broken: { watcher: {}, isBuilding: true, stopWatching: async () => { throw new Error('stop failed'); } },
			healthy: { watcher: {}, isBuilding: true, stopWatching: async () => { stopped.push('healthy'); } }
		}
	});
	await utils.stopActiveComponents();
	assert.ok(lines.some(line => /Failed to stop config file watcher/.test(line)));
	assert.ok(lines.some(line => /Failed to stop server/.test(line)));
	assert.ok(lines.some(line => /Failed to stop watcher for Object/.test(line)));
	assert.equal(project.configWatcher, null);
	assert.equal(project.validationWatcher, null);
	assert.equal(project.components.healthy.isBuilding, false);
	assert.deepEqual(stopped.sort(), ['healthy', 'validation']);
	assert.deepEqual(flushed, [true]);
});

