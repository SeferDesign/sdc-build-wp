test('adding a block tracks it, watches its source and reports background failures', async t => {
	await withProject(t, { config: {} });
	const component = new BlocksComponent();
	const logs = [];
	component.log = (type, message) => logs.push({ type, message });
	const watched = [];
	component.watcher = { add: file => watched.push(file) };
	component.globs = [];
	const rebuild = t.mock.method(component, 'rebuildDependencyMap', async () => {});
	const build = t.mock.method(component, 'build', async () => true);

	component.addBlock('/project/blocks/new');
	component.addBlock('/project/blocks/new');
	assert.deepEqual(component.globs, ['/project/blocks/new']);
	assert.deepEqual(watched, ['/project/blocks/new/src']);
	assert.deepEqual(rebuild.mock.calls[0].arguments[0], ['/project/blocks/new']);
	assert.equal(build.mock.callCount(), 1);

	rebuild.mock.mockImplementation(async () => { throw new Error('map failed'); });
	build.mock.mockImplementation(async () => { throw new Error('build failed'); });
	component.addBlock('/project/blocks/broken');
	await new Promise(resolve => setImmediate(resolve));
	assert.ok(logs.some(entry => /Failed to discover dependencies for new block .*broken: map failed/.test(entry.message)));
	assert.ok(logs.some(entry => /Failed initial build for new block .*broken/.test(entry.message)));
});

