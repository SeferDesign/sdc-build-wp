test('compiler paths are mapped back through symlinked project directories', async t => {
	const real = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'sdc-link-target-')));
	const link = `${real}-link`;
	await fs.symlink(real, link);
	t.after(async () => { await fs.rm(link); await fs.rm(real, { recursive: true, force: true }); });
	const component = new BaseComponent();
	component.project = { ...project, path: link };
	assert.equal(component.normalizeProjectPath(path.join(real, 'a/b.scss')), path.join(link, 'a/b.scss'));
	assert.equal(component.normalizeProjectPath(real), link);
	assert.equal(component.normalizeProjectPath('/somewhere/else.scss'), '/somewhere/else.scss');
	assert.equal(component.normalizeProjectPath(`${real}-sibling/x.scss`), `${real}-sibling/x.scss`);
	component.project = { ...project, path: path.join(real, 'does-not-exist') };
	assert.equal(component.normalizeProjectPath('/x/y.scss'), '/x/y.scss');
	assert.deepEqual(component.getCachedDiscoveredDependencies('/in', '/out'), []);
	component.project = { ...project, argv: { ci: true } };
	assert.equal(component.shouldFixSource, false);
	component.project = { ...project, argv: {} };
	assert.equal(component.shouldFixSource, true);
});

