function swap(t, target, changes) {
	const originals = Object.fromEntries(Object.keys(changes).map(key => [key, target[key]]));
	Object.assign(target, changes);
	t.after(() => Object.assign(target, originals));
}

test('theme.json generates Sass tokens for custom settings, layout, breakpoints, fonts, colors and gradients', async t => {
	const root = await fs.mkdtemp(path.join(os.tmpdir(), 'sdc-tokens-'));
	t.after(() => fs.rm(root, { recursive: true, force: true }));
	const component = new StyleComponent();
	component.log = () => {};
	const scss = path.join(root, '_theme.scss');
	component.project = { ...project, path: root, paths: { ...project.paths, theme: { json: path.join(root, 'theme.json'), scss } } };
	const generate = async theme => {
		await fs.writeFile(path.join(root, 'theme.json'), JSON.stringify(theme));
		await component.buildTheme();
		return fs.readFile(scss, 'utf8');
	};

	const tokens = await generate({
		settings: {
			custom: {
				dirDist: 'dist',
				lineHeight: 1.5,
				spacing: { small: '1rem', largeGap: '2rem' },
				'breakpoints-rem': { sm: 40, md: '60rem' },
				'breakpoint-mobile': 'md'
			},
			layout: { contentSize: '640px', wideSize: '1200px' },
			typography: { fontFamilies: [{ slug: 'body', fontFamily: 'Inter, sans-serif' }] },
			color: {
				palette: [{ slug: 'brand', color: '#123456' }],
				gradients: [{ slug: 'sunset', gradient: 'linear-gradient(#fff, #000)' }]
			}
		},
		styles: { typography: { fontSize: '16px' } }
	});
	assert.match(tokens, /^\/\/ This file is automatically generated from theme\.json/);
	for (const expected of [
		'$themeDirDist: "dist"; // --wp--custom--dir-dist',
		'$lineHeight: "1.5"; // --wp--custom--line-height',
		'$spacing-small: "1rem"; // --wp--custom--spacing--small',
		'$spacing-largeGap: "2rem"; // --wp--custom--spacing--large-gap',
		'$global-content-size: 640px;',
		'$global-wide-size: 1200px;',
		'$font-size-base: 16px;',
		'$screen-sm: 40rem;',
		'$screen-sm-px: 640px;',
		'$screen-md: 60rem;',
		'$screen-md-px: 960px;',
		'$mobile-breakpoint: $screen-md;',
		'$mobile-breakpoint-px: $screen-md-px;',
		'\t\'desktop\': $mobile-breakpoint,\n\t\'mobile\': $mobile-breakpoint-px - 1',
		'$body: Inter, sans-serif; // --wp--preset--font-family--body',
		'$brand: #123456; // --wp--preset--color--brand',
		'\t"brand": var(--wp--preset--color--brand),',
		'$gradient-sunset: linear-gradient(#fff, #000); // --wp--preset--gradient--sunset'
	]) {
		assert.ok(tokens.includes(expected), `missing ${expected}\n${tokens}`);
	}

	// A non-pixel base font size falls back to 16px for pixel breakpoints, and breakpoints need one.
	const rem = await generate({ settings: { custom: { 'breakpoints-rem': { lg: 50 } } }, styles: { typography: { fontSize: '1rem' } } });
	assert.match(rem, /\$screen-lg-px: 800px;/);
	assert.doesNotMatch(rem, /mobile-breakpoint/);
	const noBase = await generate({ settings: { custom: { 'breakpoints-rem': { lg: 50 } } } });
	assert.doesNotMatch(noBase, /screen-lg|font-size-base/);
	assert.equal(await generate({}), '// This file is automatically generated from theme.json. Do not edit.\n');
});

test('script changes rebuild the blocks that depend on them and tolerate block failures', async t => {
	const component = new ScriptsComponent();
	const processed = [];
	const notified = [];
	const blocks = {
		globs: [],
		getAffectedBlocks: () => new Set(['/blocks/one', '/blocks/two']),
		process: async block => {
			if (block === '/blocks/two') { throw new Error('block failed'); }
			processed.push(block);
		}
	};
	component.project = { ...project, components: { blocks, server: { server: { notify: message => notified.push(message) } } } };
	await component.checkAndRebuildAffectedBlocks('/shared.js');
	assert.deepEqual(processed, ['/blocks/one']);
	assert.equal(notified.length, 2);

	blocks.getAffectedBlocks = () => new Set();
	await component.checkAndRebuildAffectedBlocks('/unrelated.js');
	assert.equal(processed.length, 1);
	component.project = { ...project, components: {} };
	await component.checkAndRebuildAffectedBlocks('/shared.js');
	component.project = { ...project, components: { blocks: {} } };
	await component.checkAndRebuildAffectedBlocks('/shared.js');
});

